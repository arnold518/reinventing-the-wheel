"""The generated session header a long game is compiled with."""

def session_header(plan):
    """SESSION_STEPS and the Sokoban puzzles for the guest; the batches only
    for the host reference driver (they reach the guest as button events)."""
    batches=plan['batches']
    lines=['/* Generated by tools/rv32im/build-guests.py; do not edit. */','#pragma once',
           f'#define SESSION_STEPS {len(batches)}',f'#define SESSION_LEVELS {len(plan["levels"])}',
           '#ifdef SESSION_REFERENCE_DRIVER',
           'static const unsigned char session_batch_sizes[]={'+','.join(str(len(b)) for b in batches)+'};',
           'static const unsigned char session_batches[][7][2]={']
    lines+=['{'+','.join('{'+str(b)+','+str(int(d))+'}' for b,d in batch)+'},' for batch in batches]
    lines+=['};','#endif','#if GAME_KIND == 2','static const unsigned char session_levels[][64]={']
    lines+=['{'+','.join(map(str,level))+'},' for level in plan['levels']]
    lines+=['};','static const unsigned char session_players[][2]={']
    lines+=['{'+','.join(map(str,player))+'},' for player in plan['players']]
    lines+=['};','#endif']
    return '\n'.join(lines)+'\n'
