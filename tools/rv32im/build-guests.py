#!/usr/bin/env python3
"""Build and audit the additive freestanding RV32IM device/game fixtures."""
import argparse, hashlib, json, pathlib, re, subprocess
ROOT=pathlib.Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--compiler',type=pathlib.Path,required=True)
p.add_argument('--output',type=pathlib.Path,default=ROOT/'tests/fixtures/rv32im/games')
a=p.parse_args();a.output.mkdir(parents=True,exist_ok=True)
guest=ROOT/'tools/rv32im/guest'
flags=['-march=rv32im','-mabi=ilp32','-msmall-data-limit=0','-mno-relax','-Os','-ffreestanding','-fno-builtin','-fno-stack-protector','-nostdlib','-nostartfiles','-ffunction-sections','-fdata-sections','-Wl,--gc-sections','-Wl,--no-relax','-Wl,--build-id=none','-T',str(guest/'link.ld')]
allowed=set('lui auipc jal jalr beq bne blt bge bltu bgeu lb lh lw lbu lhu sb sh sw addi slti sltiu xori ori andi slli srli srai add sub sll slt sltu xor srl sra or and fence ecall ebreak mul mulh mulhsu mulhu div divu rem remu'.split())
sha=lambda data:hashlib.sha256(data).hexdigest()
compiler=a.compiler.resolve();objdump=compiler.with_name(compiler.name.removesuffix('gcc')+'objdump')
manifest={'version':1,'isa':'rv32im','abi':'ilp32','compiler':subprocess.check_output([str(compiler),'--version'],text=True).splitlines()[0], 'compilerSha256':sha(compiler.read_bytes()),'flags':flags[:-1]+['guest/link.ld'],'sources':{f.name:sha(f.read_bytes()) for f in sorted(guest.iterdir()) if f.suffix in ('.c','.h','.S','.ld')},'guests':[]}
cases=[
    (0,'bringup',0,0,0,[(1,True)]),
    (1,'2048',3,0,0,[(3,True),(1,True),(5,True)]),
    (2,'sokoban',3,0,0,[(1,True),(5,True),(0,True)]),
    (3,'snake',3,0,0,[(0,True),(0,False),(6,True),(5,True)]),
    (4,'pong',3,0,0,[(7,True),(2,True),(6,True)]),
    (5,'tetris',3,0,0,[(0,True),(4,True),(5,True)]),
    (1,'2048-merge',1,1,0,[(3,True)]),
    (5,'tetris-line-clear',1,2,0,[(4,True)]),
    (4,'pong-rally',1,3,16,[(6,True)]),
    (3,'snake-wall',2,4,0,[(6,True),(6,True)]),
]
for kind,name,actions,preset,autoticks,events in cases:
    elf=a.output/(name+'.elf');sources=['start.S','platform.c','bringup.c'] if not kind else ['start.S','platform.c','games.c','main.c']
    defines={'GAME_KIND':kind,'GAME_ACTIONS':actions,'GAME_PRESET':preset,'GAME_AUTOTICKS':autoticks}
    subprocess.run([str(compiler),*flags,*[f'-D{k}={v}' for k,v in defines.items()],*[str(guest/f) for f in sources],'-o',str(elf)],check=True)
    disasm=subprocess.check_output([str(objdump),'-d','-M','no-aliases',str(elf)],text=True).replace(str(elf),name+'.elf')
    ops=[]
    for line in disasm.splitlines():
        m=re.match(r'\s*[0-9a-f]+:\s+([0-9a-f]+)\s+(\w+)',line)
        if m:
            bits,op=m.groups()
            if len(bits)!=8 or op not in allowed:raise SystemExit('Outside RV32IM: '+line)
            ops.append(op)
    (a.output/(name+'.disasm.txt')).write_text(disasm)
    # Unit clock: reset release at 2000, origin 3000, period 1000. Inputs
    # arrive after falling edges, before the guest first polls the FIFO.
    script={'version':1,'clockPeriod':'1000','resetRelease':'2000','origin':'3000','events':[{'tick':str(3000+(i+1)*1000+501),'sequence':i+1,'device':'buttons','button':button,'down':down} for i,(button,down) in enumerate(events)]}
    script_bytes=(json.dumps(script,indent=2)+'\n').encode();(a.output/(name+'.input.json')).write_bytes(script_bytes)
    manifest['guests'].append({'id':kind,'name':name,'elf':elf.name,'elfSha256':sha(elf.read_bytes()),'script':name+'.input.json','scriptSha256':sha(script_bytes),'instructions':len(ops),'operations':sorted(set(ops)),'downEvents':sum(down for _,down in events),'defines':defines,'presentations':actions+autoticks+1 if kind else 2,'reportActions':actions+autoticks})
    print(name,len(ops),'instructions',len(elf.read_bytes()),'ELF bytes')
(a.output/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
# Embed the exact fixture bytes and input events for FS-free WebAssembly.
lines=['// Generated by tools/rv32im/build-guests.py; do not edit.',
       'const std::vector<Fixture>& fixtures() {', '    static const std::vector<Fixture> value{']
for f in manifest['guests']:
    script=json.loads((a.output/f['script']).read_text());raw=(a.output/f['elf']).read_bytes().hex()
    lines.append('        {"'+f['name']+'","'+f['elfSha256']+'","'+f['scriptSha256']+'",')
    lines.extend('            "'+raw[i:i+128]+'"' for i in range(0,len(raw),128))
    lines.append('            ,'+str(f['defines']['GAME_AUTOTICKS'])+'u,{'+','.join('{'+e['tick']+'ULL,'+str(e['sequence'])+'ULL,'+str(e['button'])+','+str(e['down']).lower()+'}' for e in script['events'])+'}},')
lines.extend(['    };','    return value;','}'])
(ROOT/'src/runtime/RecordedGuestFixtures.generated.inc').write_text('\n'.join(lines)+'\n')
