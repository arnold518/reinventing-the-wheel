#!/usr/bin/env python3
"""Rebuild the scoped RV32IM smoke fixture; existing RV32I build flags are untouched."""
import argparse
import hashlib
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--compiler', required=True, type=pathlib.Path)
p.add_argument('--output', type=pathlib.Path, default=ROOT / 'tests/fixtures/rv32im')
a = p.parse_args()
a.output.mkdir(parents=True, exist_ok=True)
fixture = ROOT / 'tests/fixtures/rv32im'
flags = ['-march=rv32im', '-mabi=ilp32', '-msmall-data-limit=0', '-mno-relax',
         '-O1', '-ffreestanding', '-fno-builtin', '-nostdlib', '-nostartfiles',
         '-Wl,--no-relax', '-Wl,--build-id=none', '-T', str(fixture / 'link.ld')]
elf = a.output / 'smoke.elf'
subprocess.run([str(a.compiler), *flags, str(fixture / 'start.S'),
                str(fixture / 'smoke.c'), '-o', str(elf)], check=True)
objdump = a.compiler.with_name(a.compiler.name.removesuffix('gcc') + 'objdump')
disasm = subprocess.check_output([str(objdump), '-d', '-M', 'no-aliases', str(elf)], text=True)
# Every emitted text instruction is a 32-bit RV32I or M instruction. Decode and
# execution are checked independently by RV32IMCompiledProgramTest as well.
allowed = set('lui auipc jal jalr beq bne blt bge bltu bgeu lb lh lw lbu lhu sb sh sw addi slti sltiu xori ori andi slli srli srai add sub sll slt sltu xor srl sra or and fence ecall ebreak mul mulh mulhsu mulhu div divu rem remu'.split())
ops = []
for line in disasm.splitlines():
    match = re.match(r'\s*[0-9a-f]+:\s+([0-9a-f]+)\s+(\w+)', line)
    if match:
        bits, op = match.groups()
        if len(bits) != 8 or op not in allowed:
            raise SystemExit(f'Instruction outside RV32IM: {line}')
        ops.append(op)
required = set('mul mulhu div divu rem remu'.split())
if not required.issubset(ops):
    raise SystemExit(f'Missing M instructions: {required - set(ops)}')
(a.output / 'smoke.disasm.txt').write_text(disasm.replace(str(elf), 'smoke.elf'))
(a.output / 'smoke.elf.sha256').write_text(hashlib.sha256(elf.read_bytes()).hexdigest() + '  smoke.elf\n')
version = subprocess.check_output([str(a.compiler), '--version'], text=True).splitlines()[0]
multilib = subprocess.check_output([str(a.compiler), '-march=rv32im', '-mabi=ilp32', '--print-multi-directory'], text=True).strip()
with a.compiler.open('rb') as compiler_file:
    compiler_hash = hashlib.file_digest(compiler_file, 'sha256').hexdigest()
(a.output / 'toolchain.txt').write_text(f'{version}\ncompiler SHA256: {compiler_hash}\nmultilib: {multilib}\nflags: {" ".join(flags[:-2])} -T link.ld\ntext instructions: {len(ops)}\n')
print(f'{elf}: {len(ops)} instructions; six compiler-selected M operations present; multilib {multilib}')

# Keep the exact audited fixture available to the FS-free WASM verifier.
raw = elf.read_bytes()
lines = ['// Generated by tools/rv32im/build-smoke.py; do not edit.',
         'std::vector<uint8_t> rv32imSmokeElfBytes() { return {']
lines.extend('    ' + ','.join(str(b) for b in raw[i:i+32]) + ',' for i in range(0,len(raw),32))
lines.append('}; }')
(ROOT / 'src/tests/RV32IMSmokeImage.generated.inc').write_text('\n'.join(lines) + '\n')
