// The delay table proven on the gate-level form of a part, for the compact
// implementation `implementation_id` built with `parameters`. Null when no
// table has been generated for it; the part then keeps its single delay.
//
// A part built with other parameters has a table only where the generator
// proved that exact combination (the advanced core for each prediction
// policy).
//
// A memory built with a word count is given a table estimated from the two
// largest sizes that can be built from gates (64 and 128 words): each delay
// keeps growing per doubling as it did between them. Such a table says
// "ESTIMATE" in its evidence. A ROM image, host budgets and device phase
// timings do not change which table applies.
//
// The tables are generated by tools/timing/PartDelayTables.cpp into
// src/components/selection/ProvenPartDelays.generated.inc.
const PartDelays* provenPartDelays(const std::string& implementation_id, const ParameterMap& parameters);
// An on-chip SRAM part of `subarrays` subarrays (N >= 4), from the tables
// proven at 1, 2 and 4 subarrays. A delay through the array crosses two
// global wires (in and out) of wire_per_side x side(N) each, side(N) the
// subarray grid's side, and grows by a per level of the decoder and return
// multiplexer (log2 N): d(N) = d(4) + a (log2 N - 2) + 2 wire_per_side
// (side(N) - side(4)), with a = d(4) - d(2). A delay that does not change
// from 1 to 4 subarrays does not depend on the array and stays.
PartDelays sramSubarrayEstimate(const PartDelays& one, const PartDelays& two, const PartDelays& four, size_t subarrays,
                                size_t wire_per_side);

// Contracts whose gate-level form gives no gate list: too large, a loop, or
// a stored state that is not a flip-flop (see
// analysis/DelayTwin.hpp), generated into NoGateList.generated.inc.
const std::set<std::string>& partsWithoutGateList();

// The generated tables of each timing profile, one source file each.
const std::map<std::string, PartDelays>& provenPartDelaysUnit();
const std::map<std::string, PartDelays>& provenPartDelaysEmbedded();
const std::map<std::string, PartDelays>& provenPartDelaysDesktop();

// Every implementation that has a table.
std::vector<std::string> provenPartDelayImplementations();

